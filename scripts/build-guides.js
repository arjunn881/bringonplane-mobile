const fs = require('fs');
const path = require('path');

const ARTICLES_DIR = path.join(__dirname, '..', '..', 'Bringonplabe', 'src', 'data', 'articles');
const OUT_DIR = path.join(__dirname, '..', 'src', 'data');

if (!fs.existsSync(OUT_DIR)) fs.mkdirSync(OUT_DIR, { recursive: true });

// 1. Extract Guides
const files = fs.readdirSync(ARTICLES_DIR).filter(f => f.endsWith('.md'));
const guides = files.map(f => {
  const content = fs.readFileSync(path.join(ARTICLES_DIR, f), 'utf8');
  const titleMatch = content.match(/title:\s*["']?(.*?)["']?\r?\n/);
  const descMatch = content.match(/description:\s*["']?(.*?)["']?\r?\n/);
  const catMatch = content.match(/category:\s*["']?(.*?)["']?\r?\n/);
  const dateMatch = content.match(/lastUpdated:\s*["']?(.*?)["']?\r?\n/);
  
  // Extract body markdown after frontmatter (--- ... ---)
  const parts = content.split(/---/);
  const body = parts.length >= 3 ? parts.slice(2).join('---').trim() : '';

  return {
    slug: f.replace('.md', ''),
    title: titleMatch ? titleMatch[1].replace(/["']/g, '').trim() : f.replace('.md', ''),
    description: descMatch ? descMatch[1].replace(/["']/g, '').trim() : '',
    category: catMatch ? catMatch[1].replace(/["']/g, '').trim() : 'Travel Guide',
    lastUpdated: dateMatch ? dateMatch[1].trim() : '2026-08-01',
    body: body.slice(0, 3000), // Preview / readable body
  };
});

const guidesTs = `// AUTO-GENERATED by scripts/build-all-data.js — DO NOT EDIT MANUALLY
export interface Guide {
  slug: string;
  title: string;
  description: string;
  category: string;
  lastUpdated: string;
  body: string;
}

export const ALL_GUIDES: Guide[] = ${JSON.stringify(guides, null, 2)};

export function getGuide(slug: string): Guide | undefined {
  return ALL_GUIDES.find(g => g.slug === slug);
}
`;

fs.writeFileSync(path.join(OUT_DIR, 'guides.ts'), guidesTs, 'utf8');
console.log(`[build] Built ${guides.length} guides in guides.ts`);
